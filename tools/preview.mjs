/**
 * Build the side-by-side visual proof for the plugin.
 *
 * Emits two standalone pages that differ in exactly one way — whether the
 * plugin's generated stylesheet is present — while both load the real shell and
 * ui-theme stylesheets exported from the running DSH build.
 *
 * Run: node tools/preview.mjs [outputDir]
 * Then screenshot `preview-default.html` and `preview-plugin.html`.
 */

import fs from "node:fs";
import path from "node:path";
import { loadClient, root } from "./load-client.mjs";
import { DEMO_STATE, renderPage, writeFixtures } from "./harness.mjs";

const outDir = path.resolve(process.argv[2] || path.join(root, "test", "out"));
fs.mkdirSync(outDir, { recursive: true });

const { internals } = loadClient();
const pluginCss = internals.buildCss(internals.normalizeState(DEMO_STATE));

writeFixtures(outDir);
fs.writeFileSync(path.join(outDir, "plugin.css"), pluginCss, "utf8");
fs.writeFileSync(path.join(outDir, "preview-default.html"), renderPage({ withPlugin: false }), "utf8");
fs.writeFileSync(path.join(outDir, "preview-plugin.html"), renderPage({ withPlugin: true }), "utf8");

console.log(`wrote ${outDir}`);
console.log("  preview-default.html  (no plugin stylesheet)");
console.log("  preview-plugin.html   (plugin stylesheet applied)");
console.log(`  plugin.css            (${pluginCss.length} chars, generated by the real buildCss)`);
